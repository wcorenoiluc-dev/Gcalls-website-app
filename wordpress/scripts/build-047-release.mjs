#!/usr/bin/env node
/**
 * GCALLS-045 — CONTENT-ONLY release: Core 0.10.8.
 *
 * WHY THE FORM IS NOT IN HERE
 * The owner approved deploying the GCALLS-044 CONTENT. The 042 candidate also
 * carries a working lead form, and §2 of this brief is explicit: a working form
 * must not go live until cache and nonce handling has been verified. That
 * verification needs edge-cache access this session does not have — a cached
 * nonce is served to the next visitor, which breaks submissions for everyone
 * after the first.
 *
 * So the content ships and the form does not. `/lien-he/` keeps the note it
 * shows today: Content_Pages::form_slot() checks `class_exists(Leads)` before
 * rendering a form, so with the class absent it fail-closes on its own rather
 * than needing the manifest edited back.
 *
 * The form release becomes 0.10.8, after cache and SMTP are settled.
 *
 * WHY THIS IS NOT "ZIP THE WORKING TREE"
 * The working tree is NOT the release base. Measured: its gcalls-core.php
 * carries version 0.9.7 (a downgrade from 0.10.1), and it REPLACED the
 * `Content_Pages` require and init with `Leads` — so packaging the working tree
 * would ship a lower version number and silently drop the renderer for all
 * thirteen content routes. Core 0.10.2 is therefore assembled as exact 0.10.1
 * plus a named list of reviewed changes, and asserted to be a strict superset.
 *
 * The form backend is a separate release. Nothing named below brings it, and
 * the build fails if any leads artifact or `Leads::` call reaches the package.
 */
import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'
import crypto from 'node:crypto'

const REPO = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../..')
const OUT = process.env.GCALLS_RELEASE_OUT || path.join(REPO, 'wordpress/.release-047')
const ZIP_0101 = process.env.GCALLS_0101_ZIP ||
  '/Users/macos/Desktop/gcalls-core-0.10.1-CANDIDATE-do-not-deploy-yet/gcalls-core-0.10.1.zip'
const ZIP_0101_SHA = '52ffe873880a304714a858ff69e680ec48c6d741cf90e744d4e46d0f695a0c48'

const CORE_SRC = path.join(REPO, 'wordpress/wp-content/plugins/gcalls-core')
const THEME_SRC = path.join(REPO, 'wordpress/wp-content/themes/gcalls-theme')

const sha = (f) => crypto.createHash('sha256').update(fs.readFileSync(f)).digest('hex')
const die = (m) => { console.error(`FATAL: ${m}`); process.exit(2) }

/* Reviewed changes to Core, and nothing else. */
const CORE_ADD = [
  // GCALLS-047: the stylesheet for the gcalls-cp__* markup, and the locked
  // shape the completeness test reads.
  'assets/css/content-pages.css',
  'data/content-inventory.json',
  'includes/class-icons.php',
  'includes/class-sections.php',
  'data/section-components.json',
  'data/media-frames.json',
]
const CORE_MODIFY = [
  // GCALLS-040 §B: the eighteen emitted sections regrouped into the thirteen
  // compositions HomePage.tsx has, at the 033 rhythm. Regenerated by
  // wordpress/scripts/build-homepage-template.mjs; content is unchanged
  // widget-for-widget.
  'data/homepage-elementor.json',
  'data/homepage-inventory.json',
  // Renders a heading over an empty grid when every card in a section is
  // blank — 14 such sections ship in 0.10.1's own content-pages.json.
  'includes/class-content-pages.php',
  // GCALLS-041 §2: 32 navigation destinations restored, each verified 200 on
  // live; informational cards deliberately untouched.
  'data/content-pages.json',
  'includes/class-mockups.php',
  'assets/css/mockups.css',
  'data/product-pages.json',
]
/* ------------------------------------------------------------------ *
 * GCALLS-040 §A — APPROVED REMOVALS
 * ------------------------------------------------------------------ *
 * GCALLS-039 shipped six REFUSED images inside the package because the gate it
 * had to satisfy was "strict superset of every file in 0.10.1". They could not
 * render — the registry fails closed — but they were still fetchable by direct
 * URL once deployed, which is a real exposure dressed up as a passing test.
 *
 * The gate is now FUNCTIONAL_PRESERVATION_WITH_APPROVED_REMOVALS: every route,
 * every piece of content, every CTA and every working feature of 0.10.1 must
 * survive, and the ONLY files allowed to disappear are the ones named here.
 *
 * Each is pinned by SHA-256, not by name or glob. If a file at one of these
 * paths does not hash to the recorded value it is NOT the image that was
 * reviewed, and the build stops rather than deleting something unexamined.
 *
 * The originals stay in the repository: this removes them from the ARTIFACT,
 * not from the evidence. Nothing here touches git history or live media.
 */
const APPROVED_REMOVALS = [
  { id: 'webphone-overview', file: 'assets/images/product-gallery/webphone-overview.webp', sha256: '1ea97958d1d26af6fc3ffda8b32b4d929b51b24dc568c9f4ff745820d705c965' },
  { id: 'customer-profile', file: 'assets/images/product-gallery/customer-profile.webp', sha256: '926de3b7385b311bed87d758d04f0b631423b3c6a15bc7a09b29786a13cc8099' },
  { id: 'call-history', file: 'assets/images/product-gallery/call-history.webp', sha256: '0da67896db7940b1d727e508d8183e34e0106d18f75fef95c9e006254c1bf675' },
  { id: 'analytics-dashboard', file: 'assets/images/product-gallery/analytics-dashboard.webp', sha256: '3369ece36e9ac83449d31f44d24ed386ebecdcca9cd54bbc8db5a7bfec5767b2' },
  { id: 'agent-performance', file: 'assets/images/product-gallery/agent-performance.webp', sha256: '6bbaf13f3e8d8360859c54e438a3f6555d0a38adbcceed6832a096d944e796ca' },
  { id: 'click-to-call', file: 'assets/images/product-gallery/click-to-call.webp', sha256: '72b8782477a6948d276868ffd6db975bd57aa10d1bd34b07c00d79b45c557b67' },
]

/* Never, under any name. */
const FORBIDDEN = [
  'includes/class-leads.php', 'assets/js/lead-form.js',
  'assets/css/lead-form.css', 'tests/leads-test.php',
]

fs.rmSync(OUT, { recursive: true, force: true })
fs.mkdirSync(OUT, { recursive: true })

/* ---- 1. exact 0.10.1, hash-checked ---- */
if (!fs.existsSync(ZIP_0101)) die(`0.10.1 zip not found: ${ZIP_0101}`)
if (sha(ZIP_0101) !== ZIP_0101_SHA) die(`0.10.1 zip hash mismatch\n  want ${ZIP_0101_SHA}\n  got  ${sha(ZIP_0101)}`)

const base = path.join(OUT, '_base')
fs.mkdirSync(base, { recursive: true })
execFileSync('unzip', ['-q', '-o', ZIP_0101, '-d', base])
const baseCore = path.join(base, 'gcalls-core')
if (!fs.existsSync(baseCore)) die('0.10.1 zip did not contain gcalls-core/')

const build = path.join(OUT, 'gcalls-core')
fs.cpSync(baseCore, build, { recursive: true })

/* ---- 2. overlay the reviewed changes ---- */
for (const rel of [...CORE_ADD, ...CORE_MODIFY]) {
  const src = path.join(CORE_SRC, rel)
  if (!fs.existsSync(src)) die(`reviewed file missing from working tree: ${rel}`)
  fs.mkdirSync(path.dirname(path.join(build, rel)), { recursive: true })
  fs.copyFileSync(src, path.join(build, rel))
}

/* ---- 2b. remove the approved REFUSED assets, each verified by hash ---- */
const registry = JSON.parse(fs.readFileSync(path.join(build, 'data/media-frames.json'), 'utf8'))
for (const item of APPROVED_REMOVALS) {
  const target = path.join(build, item.file)
  if (!fs.existsSync(target)) die(`approved removal not found in the build: ${item.file}`)
  const actual = sha(target)
  if (actual !== item.sha256) {
    die(`${item.file} is not the reviewed image\n  want ${item.sha256}\n  got  ${actual}`)
  }
  // Cross-check the registry rather than trusting this table alone: an image
  // may only be removed if the registry independently calls it REFUSED.
  const entry = registry.frames?.[item.id]
  if (!entry) die(`${item.id} is not in the media registry — refusing to remove an unregistered file`)
  if (entry.verdict === 'PASS') die(`${item.id} is PASS in the registry — removing it would break a rendering frame`)
  if (entry.file !== path.basename(item.file)) die(`${item.id} registry filename disagrees with the removal table`)
  fs.rmSync(target)
}

/* Every frame the registry still calls PASS must survive, or a product page
 * loses a picture and the "no broken image" gate would be the first to know. */
for (const [id, frame] of Object.entries(registry.frames ?? {})) {
  if (frame.verdict !== 'PASS') continue
  const kept = path.join(build, 'assets/images/product-gallery', frame.file)
  if (!fs.existsSync(kept)) die(`PASS frame ${id} lost its file: ${frame.file}`)
}

/* ---- 3. class-shortcodes.php: renderer changes WITHOUT the form runtime ----
 * The working-tree file has the verified hero/final CTA and product_page
 * changes, and also the live form: lead_form() rewritten to post to Leads, plus
 * two new helpers. Those three functions are reverted to 0.10.1, which renders
 * the form as a disabled panel and references no Leads class at all. */
const takeFn = (src, name) => {
  const start = src.indexOf(`\tpublic static function ${name}(`) >= 0
    ? src.indexOf(`\tpublic static function ${name}(`)
    : src.indexOf(`\tprivate static function ${name}(`)
  if (start < 0) return null
  // walk back over the docblock
  let docStart = src.lastIndexOf('\t/**', start)
  const between = src.slice(docStart, start)
  if (docStart < 0 || between.includes('}\n')) docStart = start
  const end = src.indexOf('\n\t}\n', start) + 4
  return { start: docStart, end, text: src.slice(docStart, end) }
}

let sc = fs.readFileSync(path.join(CORE_SRC, 'includes/class-shortcodes.php'), 'utf8')
const sc0101 = fs.readFileSync(path.join(baseCore, 'includes/class-shortcodes.php'), 'utf8')

for (const fn of ['lead_state', 'lead_current_path']) {
  const cut = takeFn(sc, fn)
  if (cut) sc = sc.slice(0, cut.start) + sc.slice(cut.end)
}
const mine = takeFn(sc, 'lead_form')
const theirs = takeFn(sc0101, 'lead_form')
if (!mine || !theirs) die('could not locate lead_form() in both versions')
sc = sc.slice(0, mine.start) + theirs.text + sc.slice(mine.end)
fs.writeFileSync(path.join(build, 'includes/class-shortcodes.php'), sc)

/* ---- 4. bootstrap: 0.10.1's, at 0.10.2, plus the two new requires ---- */
let boot = fs.readFileSync(path.join(baseCore, 'gcalls-core.php'), 'utf8')
boot = boot.replace(' * Version:           0.10.1', ' * Version:           0.10.8')
boot = boot.replace("const VERSION = '0.10.1';", "const VERSION = '0.10.8';")
boot = boot.replace(
  "require_once GCALLS_CORE_DIR . 'includes/class-shortcodes.php';",
  "require_once GCALLS_CORE_DIR . 'includes/class-icons.php';\n" +
  "require_once GCALLS_CORE_DIR . 'includes/class-sections.php';\n" +
  "require_once GCALLS_CORE_DIR . 'includes/class-shortcodes.php';")
if (!boot.includes('class-icons.php')) die('could not add the new requires to the bootstrap')
fs.writeFileSync(path.join(build, 'gcalls-core.php'), boot)

/* ---- 5. theme 0.8.6 from the live 0.8.5 tree ---- */
const THEME_CSS_0085 = 'aea2b9536c85c01799a9c65e55545106fddb0d49968b6b56b9c3b85c97e3f6f1'
if (sha(path.join(THEME_SRC, 'assets/css/theme.css')) !== THEME_CSS_0085) {
  die('theme.css is not byte-identical to live 0.8.5 — wrong theme base')
}
const themeBuild = path.join(OUT, 'gcalls-theme')
fs.cpSync(THEME_SRC, themeBuild, { recursive: true })
let style = fs.readFileSync(path.join(themeBuild, 'style.css'), 'utf8')
style = style.replace('Version: 0.8.5', 'Version: 0.8.6')
fs.writeFileSync(path.join(themeBuild, 'style.css'), style)

/* ---- 6. gates ---- */
const walk = (d, p = '', o = []) => {
  for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    const rel = p ? `${p}/${e.name}` : e.name
    e.isDirectory() ? walk(path.join(d, e.name), rel, o) : o.push(rel)
  }
  return o
}
const baseFiles = walk(baseCore)
const buildFiles = walk(build)

/* FUNCTIONAL_PRESERVATION_WITH_APPROVED_REMOVALS.
 *
 * Anything present in 0.10.1 and absent here must appear in APPROVED_REMOVALS.
 * A file that goes missing for any other reason — a botched copy, a rename, a
 * stray delete — still fails the build exactly as the superset rule did. */
const lost = baseFiles.filter((f) => !buildFiles.includes(f))
const approvedPaths = new Set(APPROVED_REMOVALS.map((r) => r.file))
const unapproved = lost.filter((f) => !approvedPaths.has(f))
if (unapproved.length) die(`Core 0.10.8 drops file(s) nobody approved: ${unapproved.join(', ')}`)

const notRemoved = APPROVED_REMOVALS.filter((r) => buildFiles.includes(r.file))
if (notRemoved.length) die(`approved removal(s) still in the package: ${notRemoved.map((r) => r.id).join(', ')}`)

if (lost.length !== APPROVED_REMOVALS.length) {
  die(`expected exactly ${APPROVED_REMOVALS.length} removal(s), found ${lost.length}`)
}

const leaked = buildFiles.filter((f) => FORBIDDEN.includes(f) || /lead-form|class-leads/.test(f))
if (leaked.length) die(`form artifacts leaked into Core: ${leaked.join(', ')}`)

for (const f of buildFiles.filter((f) => f.endsWith('.php'))) {
  const t = fs.readFileSync(path.join(build, f), 'utf8')
  /*
   * Strip comments first. class-content-pages.php explains the fail-closed
   * guard in prose ("Leads::assets() answers the question by..."), and a gate
   * that trips on its own documentation is a gate nobody can satisfy — the same
   * false positive the 042 build hit on `fieldset disabled`.
   */
  const code = t.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '')
  if (/\bLeads::/.test(code)) die(`executable Leads:: reference survives in ${f}`)
}

console.log(`Core 0.10.8:  ${buildFiles.length} files (0.10.1 had ${baseFiles.length}: +${buildFiles.filter((f) => !baseFiles.includes(f)).length} added, -${lost.length} approved removals)`)
console.log(`  added:    ${buildFiles.filter((f) => !baseFiles.includes(f)).join(', ')}`)
console.log(`Theme 0.8.6:  ${walk(themeBuild).length} files`)
console.log(`removed:  ${APPROVED_REMOVALS.length} approved REFUSED asset(s) — ${APPROVED_REMOVALS.map((r) => r.id).join(', ')}`)
for (const forbidden of ['includes/class-leads.php', 'assets/js/lead-form.js', 'assets/css/lead-form.css']) {
  if (buildFiles.includes(forbidden)) die(`the form must not ship in the content release: ${forbidden}`)
}
const cp = fs.readFileSync(path.join(build, 'data/content-pages.json'), 'utf8')
const pageCount = JSON.parse(cp).pages.length
if (pageCount < 31) die(`content manifest has only ${pageCount} pages — the GCALLS-044 content is missing`)
console.log(`form artifacts: 0   Leads:: references: 0   manifest pages: ${pageCount}`)
console.log(`\nstaged in ${OUT}`)
